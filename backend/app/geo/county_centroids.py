def centroid(county: str | None) -> tuple[float, float] | None:
    """Return (lat, lng) for a Texas county name, or None if unknown."""
    if not county:
        return None
    key = county.strip().upper()
    if key.endswith(" COUNTY"):
        key = key[: -len(" COUNTY")]
    hit = TX_COUNTY_CENTROIDS.get(key)
    return (hit[0], hit[1]) if hit else None
